-- Model catalog owned by the catalog module. Stores enabled models,
-- supported capabilities, provider mappings, and synced upstream costs.
-- RLS is enabled without public policies so upstream provider costs are never
-- exposed directly through Supabase; the engine owns all reads and writes.
create table if not exists public.generation_models (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  summary text not null default '',
  provider text not null,
  provider_model_key text not null,
  supported_modes text[] not null default '{}',
  supported_inputs text[] not null default '{}',
  resolutions text[] not null default '{}',
  durations_seconds int[] not null default '{}',
  aspect_ratios text[] not null default '{}',
  supports_audio boolean not null default false,
  provider_cost_micros bigint not null default 0 check (provider_cost_micros >= 0),
  provider_cost_unit text not null default 'per_image' check (provider_cost_unit in ('per_second', 'per_image')),
  sort_order int not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  unique (provider, provider_model_key)
);

create index if not exists generation_models_active_sort_idx
  on public.generation_models (active, sort_order, name);

alter table public.generation_models enable row level security;

